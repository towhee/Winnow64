/*
    LutParse -- reading .cube and HaldCLUT into a Lut3d::Table.

    WHY THIS TEST EXISTS. Both formats are a flat run of numbers whose MEANING is entirely
    in the index convention, and getting that convention wrong does not fail -- it renders
    a plausible picture with red and blue exchanged, or a table sheared along one axis.
    Neither shows up as an error anywhere.

    So the index order is proved twice, by two arguments that do not share an assumption:

      o an eight-corner 2x2x2 .cube, where each corner is a distinct primary, so a
        transposition moves a known colour to a known wrong place;
      o CROSS-FORMAT AGREEMENT -- one analytic look emitted as BOTH a .cube and a Hald
        image from the same generator, required to agree. The two formats are written by
        different code down different paths, so a transposition in either reader alone
        cannot pass, and a transposition in both would have to be the same transposition.

    The rest is refusal: every malformed file must be rejected WITH A REASON rather than
    padded, because these are untrusted downloads and a silently zero-filled table is a
    black picture nobody can explain.
*/

