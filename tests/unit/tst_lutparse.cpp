/* ---------------------------------------------------------------------------------------
   The look used by the cross-format test: channel mixing plus a per-channel curve, so it
   is neither symmetric nor separable -- a transposition cannot hide in it.
   ------------------------------------------------------------------------------------ */
static void look(float r, float g, float b, float &orr, float &og, float &ob)
{
    orr = std::min(1.0f, std::max(0.0f, 0.90f * r + 0.10f * g));
    og  = std::min(1.0f, std::max(0.0f, std::pow(g, 1.10f)));
    ob  = std::min(1.0f, std::max(0.0f, 0.80f * b + 0.20f * r));
}

/* The same look as .cube text: n^3 triplets, red fastest. */
static QByteArray asCube(int n)
{
    QByteArray out = "# generated by the test\nTITLE \"Agreement\"\n";
    out += "LUT_3D_SIZE " + QByteArray::number(n) + "\n";
    const float d = float(n - 1);
    for (int b = 0; b < n; ++b)
        for (int g = 0; g < n; ++g)
            for (int r = 0; r < n; ++r) {
                float x, y, z;
                look(float(r) / d, float(g) / d, float(b) / d, x, y, z);
                out += QByteArray::number(double(x), 'f', 6) + " " +
                       QByteArray::number(double(y), 'f', 6) + " " +
                       QByteArray::number(double(z), 'f', 6) + "\n";
            }
    return out;
}

/* The same look as a HaldCLUT image of the given level: w = L^3, cube = L^2. */
static QImage asHald(int level)
{
    const int size = level * level;
    const int w = level * level * level;
    QImage img(w, w, QImage::Format_RGB888);
    const float d = float(size - 1);
    size_t k = 0;
    for (int y = 0; y < w; ++y) {
        uchar *p = img.scanLine(y);
        for (int x = 0; x < w; ++x, ++k) {
            const int r = int(k % size_t(size));
            const int g = int((k / size_t(size)) % size_t(size));
            const int b = int(k / (size_t(size) * size_t(size)));
            float ox, oy, oz;
            look(float(r) / d, float(g) / d, float(b) / d, ox, oy, oz);
            p[x * 3 + 0] = uchar(std::lround(ox * 255.0f));
            p[x * 3 + 1] = uchar(std::lround(oy * 255.0f));
            p[x * 3 + 2] = uchar(std::lround(oz * 255.0f));
        }
    }
    return img;
}

/* An identity Hald of the given level. */
static QImage identityHald(int level)
{
    const int size = level * level;
    const int w = level * level * level;
    QImage img(w, w, QImage::Format_RGB888);
    const float d = float(size - 1);
    size_t k = 0;
    for (int y = 0; y < w; ++y) {
        uchar *p = img.scanLine(y);
        for (int x = 0; x < w; ++x, ++k) {
            const int r = int(k % size_t(size));
            const int g = int((k / size_t(size)) % size_t(size));
            const int b = int(k / (size_t(size) * size_t(size)));
            p[x * 3 + 0] = uchar(std::lround(float(r) / d * 255.0f));
            p[x * 3 + 1] = uchar(std::lround(float(g) / d * 255.0f));
            p[x * 3 + 2] = uchar(std::lround(float(b) / d * 255.0f));
        }
    }
    return img;
}

