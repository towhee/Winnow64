void TstLutParse::cubeAndHaldAgree()
{
    /*
        THE CROSS-FORMAT PROOF. One look, two encoders, two readers. Level 8 and
        LUT_3D_SIZE 64 describe the same 64-cube, so every lattice entry must match --
        and since the two files are written by different code and read by different code,
        an index transposition in either reader alone cannot survive this.
    */
    const int level = 8, n = level * level;
    Lut3d::Table fromCube, fromHald;
    QString err;
    QVERIFY2(LutParse::ParseCube(asCube(n), fromCube, &err), qPrintable(err));
    QVERIFY2(LutParse::FromHald(asHald(level), fromHald, &err), qPrintable(err));
    QCOMPARE(fromCube.size, n);
    QCOMPARE(fromHald.size, n);
    QCOMPARE(fromCube.v.size(), fromHald.v.size());

    /* Every lattice entry, within 8-bit quantisation -- the Hald's limit, not the
       cube's. */
    float worst = 0.0f;
    for (size_t i = 0; i < fromCube.v.size(); ++i)
        worst = std::max(worst, std::fabs(fromCube.v[i] - fromHald.v[i]));
    QVERIFY2(worst < 1.5f / 255.0f,
             qPrintable(QString("lattice entries differ by up to %1").arg(worst)));

    /* And off-lattice, which also exercises the sampler through both tables. */
    worst = 0.0f;
    for (int i = 0; i < 200; ++i) {
        const float x = float((i * 37) % 101) / 100.0f;
        const float y = float((i * 61) % 101) / 100.0f;
        const float z = float((i * 17) % 101) / 100.0f;
        float ar = x, ag = y, ab = z;
        float br = x, bg = y, bb = z;
        Lut3d::Apply(fromCube, ar, ag, ab);
        Lut3d::Apply(fromHald, br, bg, bb);
        worst = std::max({worst, std::fabs(ar - br), std::fabs(ag - bg),
                          std::fabs(ab - bb)});
    }
    QVERIFY2(worst < 2.5f / 255.0f,
             qPrintable(QString("off-lattice samples differ by up to %1").arg(worst)));

    /* The look is not the identity, or none of the above would mean anything. */
    float r = 0.2f, g = 0.8f, b = 0.4f;
    Lut3d::Apply(fromCube, r, g, b);
    QVERIFY2(std::fabs(r - 0.2f) > 0.01f || std::fabs(b - 0.4f) > 0.01f,
             "the agreement look is too close to the identity to prove anything");
}

/*
    OPPORTUNISTIC, and the only case here that sees a file somebody else wrote. Every
    fixture above is built in this source, which proves the reader against what the spec
    SAYS; this proves it against what tools actually emit -- Adobe's own exported LUTs,
    with their comment headers, DOMAIN lines and 6-decimal formatting. It skips where
    those files are not installed, exactly as tst_cameraprofilestore skips without
    profiles.
*/
void TstLutParse::realWorldCubesParse()
{
    const QStringList roots = {
        "/Applications/Adobe Photoshop 2026/Presets/3DLUTs",
        "/Applications/Adobe Photoshop (Beta)/Presets/3DLUTs",
        "/Applications/Adobe Photoshop 2025/Presets/3DLUTs",
    };
    QStringList files;
    for (const QString &r : roots) {
        QDir d(r);
        if (!d.exists()) continue;
        for (const QString &f : d.entryList({"*.cube", "*.CUBE"}, QDir::Files))
            files << d.filePath(f);
    }
    if (files.isEmpty()) QSKIP("no real .cube files installed on this machine");

    int parsed = 0;
    for (const QString &path : files) {
        QFile f(path);
        QVERIFY(f.open(QIODevice::ReadOnly));
        Lut3d::Table t;
        QString err;
        QVERIFY2(LutParse::ParseCube(f.readAll(), t, &err),
                 qPrintable(QString("%1: %2").arg(QFileInfo(path).fileName(), err)));
        QVERIFY2(t.isValid(), qPrintable(path));
        /* A real look must move colour somewhere, and must stay finite doing it. */
        float r = 0.3f, g = 0.55f, b = 0.72f;
        Lut3d::Apply(t, r, g, b);
        QVERIFY(std::isfinite(r) && std::isfinite(g) && std::isfinite(b));
        ++parsed;
    }
    qInfo("parsed %d real .cube files", parsed);
    QVERIFY(parsed > 0);
}

