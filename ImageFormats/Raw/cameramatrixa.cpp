bool xyzToCamStdAForModel(const QString &model, float m[3][3])
{
    const char *key = cameraMatrixKey(model);
    if (!key) return false;
    for (const EntryA &e : kTableA) {
        if (std::strcmp(e.model, key) != 0) continue;
        for (int i = 0; i < 9; ++i)
            m[i / 3][i % 3] = e.c[i] / 10000.0f;
        return true;
    }
    return false;
}
