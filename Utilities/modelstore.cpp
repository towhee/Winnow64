/* One lock covers the sidecar and the state cache; both are touched from render workers
   (through path()) as well as the GUI thread. */
QMutex g_mutex;

struct Record {                 // one line of models.json
    QString sha256;
    qint64  bytes = 0;
    qint64  mtime = 0;          // secsSinceEpoch, to spot a file changed behind our back
};

QHash<QString, Record> g_sidecar;
bool                   g_sidecarLoaded = false;

/* state() is called from the develop render paths, so it must not stat (let alone hash) on
   every call. Computed once per model per process; invalidated on download / remove. */
QHash<int, State> g_stateCache;

QString sidecarPath() { return QDir(dir()).filePath("models.json"); }

void loadSidecar()          // call with g_mutex held
{
    if (g_sidecarLoaded) return;
    g_sidecarLoaded = true;
    QFile f(sidecarPath());
    if (!f.open(QIODevice::ReadOnly)) return;
    const QJsonObject root = QJsonDocument::fromJson(f.readAll()).object();
    for (auto it = root.constBegin(); it != root.constEnd(); ++it) {
        const QJsonObject o = it.value().toObject();
        Record r;
        r.sha256 = o.value("sha256").toString();
        r.bytes  = qint64(o.value("bytes").toDouble());
        r.mtime  = qint64(o.value("mtime").toDouble());
        g_sidecar.insert(it.key(), r);
    }
}

void saveSidecar()          // call with g_mutex held
{
    QJsonObject root;
    for (auto it = g_sidecar.constBegin(); it != g_sidecar.constEnd(); ++it) {
        QJsonObject o;
        o.insert("sha256", it.value().sha256);
        o.insert("bytes",  double(it.value().bytes));
        o.insert("mtime",  double(it.value().mtime));
        root.insert(it.key(), o);
    }
    QSaveFile f(sidecarPath());
    if (!f.open(QIODevice::WriteOnly)) return;
    f.write(QJsonDocument(root).toJson(QJsonDocument::Indented));
    f.commit();
}

/* Streamed so a 198 MB model is never held in memory. */
QString hashFile(const QString &path)
{
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly)) return QString();
    QCryptographicHash h(QCryptographicHash::Sha256);
    if (!h.addData(&f)) return QString();
    return QString::fromLatin1(h.result().toHex());
}

/* Where a model would live if it were bundled beside the binary. On macOS that is
   Winnow.app/Contents/MacOS (matching how ExifTool and the Winnets are laid out). */
QString bundledPath(const ModelInfo &mi)
{
    return QDir(QCoreApplication::applicationDirPath()).filePath(QString::fromLatin1(mi.fileName));
}

QString downloadedPath(const ModelInfo &mi)
{
    return QDir(dir()).filePath(QString::fromLatin1(mi.fileName));
}

State computeState(const ModelInfo &mi)     // call with g_mutex held
{
    /* The app dir wins. That resolves the two bundled models, and it keeps a dev tree
       that still has every .onnx beside the binary working exactly as before. */
    if (QFile::exists(bundledPath(mi))) return State::Bundled;
    if (mi.bundled) return State::Missing;          // should be impossible in a real build

    const QString p = downloadedPath(mi);
    QFileInfo fi(p);
    if (!fi.exists()) return State::Missing;

    loadSidecar();
    const QString key = QString::fromLatin1(mi.fileName);
    const Record  rec = g_sidecar.value(key);
    const qint64  mtime = fi.lastModified().toSecsSinceEpoch();

    /* Fast path: the sidecar vouches for this exact file, so trust its recorded hash
       rather than re-reading 198 MB. */
    if (!rec.sha256.isEmpty() && rec.bytes == fi.size() && rec.mtime == mtime)
        return rec.sha256 == QString::fromLatin1(mi.sha256) ? State::Ready : State::Stale;

    /* No provenance (or the file moved/changed): hash it once and record the answer. */
    const QString actual = hashFile(p);
    if (actual.isEmpty()) return State::Corrupt;

    Record fresh;
    fresh.sha256 = actual;
    fresh.bytes  = fi.size();
    fresh.mtime  = mtime;
    g_sidecar.insert(key, fresh);
    saveSidecar();

    if (actual == QString::fromLatin1(mi.sha256)) return State::Ready;

    /* Intact but not what this build wants -> an older export (Stale, offer an update).
       Hashes to neither -> genuinely damaged bytes (Corrupt, offer a repair). */
    if (!rec.sha256.isEmpty() && rec.sha256 != actual) return State::Corrupt;
    return State::Stale;
}

