const QVector<ModelInfo> &catalog() { return table(); }

const ModelInfo &info(Model m)
{
    for (const ModelInfo &mi : table())
        if (mi.id == m) return mi;
    Q_ASSERT_X(false, "ModelStore::info", "model not in catalog");
    return table().first();
}

QString url(Model m)
{
    /* APPEND-ONLY. The version in the filename is what lets a build fetch exactly the
       bytes it was compiled against, years after a newer Winnow started shipping
       different weights. Never repoint this at an unversioned name. */
    static const QString kBase = QStringLiteral("https://winnow.ca/winnow/models/");
    const ModelInfo &mi = info(m);
    QString stem = QString::fromLatin1(mi.fileName);
    stem.chop(5);                                   // drop ".onnx"
    return kBase + stem + "-" + QString::number(mi.version) + ".onnx";
}

QString dir()
{
    const QString d = QStandardPaths::writableLocation(QStandardPaths::AppDataLocation)
                      + "/Models";
    QDir().mkpath(d);
    return d;
}

State state(Model m)
{
    QMutexLocker lock(&g_mutex);
    const int key = int(m);
    if (g_stateCache.contains(key)) return g_stateCache.value(key);
    const State s = computeState(info(m));
    g_stateCache.insert(key, s);
    return s;
}

void invalidate(Model m)
{
    QMutexLocker lock(&g_mutex);
    g_stateCache.remove(int(m));
}

QString path(Model m)
{
    const State s = state(m);
    if (s != State::Ready && s != State::Bundled) return QString();
    const ModelInfo &mi = info(m);
    const QString b = bundledPath(mi);
    if (QFile::exists(b)) return b;
    return downloadedPath(mi);
}

bool isAvailable(Model m) { return !path(m).isEmpty(); }

bool isAvailable(const QVector<Model> &models)
{
    for (Model m : models)
        if (!isAvailable(m)) return false;
    return true;
}

QString stateText(State s)
{
    switch (s) {
    case State::Bundled: return QObject::tr("Included with Winnow");
    case State::Ready:   return QObject::tr("Downloaded");
    case State::Missing: return QObject::tr("Not downloaded");
    case State::Stale:   return QObject::tr("Update available");
    case State::Corrupt: return QObject::tr("Damaged - re-download");
    }
    return QString();
}

bool ensure(const QVector<Model> &need, QWidget *parent)
{
    if (G::isLogger) G::log("ModelStore::ensure");

    /* Never reach for the network during automated runs -- and test mode redirects
       AppDataLocation anyway, so the features no-op exactly as they do with a model
       absent. Mirrors MW::checkForUpdate's guard. */
    if (G::isTest || G::isStressTest || QStandardPaths::isTestModeEnabled()) return false;

    QVector<Model> want;
    for (Model m : need) {
        const State s = state(m);
        if (s != State::Ready && s != State::Bundled) want << m;
    }
    if (want.isEmpty()) return true;

    qint64 total = 0;
    for (Model m : want) total += info(m).bytes;

    /* Refuse up front rather than filling the disk and failing at the last chunk. */
    const QStorageInfo storage(dir());
    if (storage.isValid() && storage.bytesAvailable() > 0
        && storage.bytesAvailable() < total + (64LL << 20)) {
        ModelDownloadDlg::reportNoSpace(total, storage.bytesAvailable(), parent);
        return false;
    }

    ModelDownloadDlg dlg(want, parent);
    const bool ok = (dlg.exec() == QDialog::Accepted);

    for (Model m : want) invalidate(m);
    return ok && isAvailable(need);
}

QVector<QString> orphans()
{
    QSet<QString> known;
    for (const ModelInfo &mi : table()) known.insert(QString::fromLatin1(mi.fileName));

    QVector<QString> out;
    const QFileInfoList entries =
        QDir(dir()).entryInfoList(QStringList() << "*.onnx", QDir::Files);
    for (const QFileInfo &fi : entries)
        if (!known.contains(fi.fileName())) out << fi.fileName();
    return out;
}

qint64 orphanBytes()
{
    qint64 total = 0;
    const QDir d(dir());
    for (const QString &name : orphans()) total += QFileInfo(d.filePath(name)).size();
    return total;
}

bool remove(Model m)
{
    const ModelInfo &mi = info(m);
    if (mi.bundled) return false;                    // not ours to delete
    const QString key = QString::fromLatin1(mi.fileName);
    const bool ok = QFile::remove(downloadedPath(mi));
    QMutexLocker lock(&g_mutex);
    loadSidecar();
    g_sidecar.remove(key);
    saveSidecar();
    g_stateCache.remove(int(m));
    return ok;
}

qint64 bytesOnDisk()
{
    qint64 total = 0;
    const QFileInfoList entries =
        QDir(dir()).entryInfoList(QStringList() << "*.onnx", QDir::Files);
    for (const QFileInfo &fi : entries) total += fi.size();
    return total;
}

void sweepPartials()
{
    const QDir d(dir());
    const QFileInfoList entries = d.entryInfoList(QStringList() << "*.part", QDir::Files);
    for (const QFileInfo &fi : entries) QFile::remove(fi.absoluteFilePath());
}

/* Called by ModelDownloadDlg once a model has been verified onto disk, so the next
   state() sees it without a restart. */
void recordDownloaded(Model m, const QString &sha256)
{
    const ModelInfo &mi = info(m);
    QFileInfo fi(downloadedPath(mi));
    QMutexLocker lock(&g_mutex);
    loadSidecar();
    Record r;
    r.sha256 = sha256;
    r.bytes  = fi.size();
    r.mtime  = fi.lastModified().toSecsSinceEpoch();
    g_sidecar.insert(QString::fromLatin1(mi.fileName), r);
    saveSidecar();
    g_stateCache.remove(int(m));
}

